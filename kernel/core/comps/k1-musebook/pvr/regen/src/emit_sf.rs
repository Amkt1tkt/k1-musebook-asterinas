//! Emit `src/rogue/sf.rs` from `pvr_rogue_fwif_sf.h`'s `stid_fmts[]`.

use std::fmt::Write as _;

use crate::{emit::GenMeta, parse::ParseError, parse_sf::StidEntry};

/// Emit a sorted `(id, group, params, fmt)` table for firmware-trace decode.
///
/// The 775 templates occupy 40,680 bytes of UTF-8, plus the `&str` headers.
/// They make the bounded firmware trace readable without an external decoder.
/// The kernel's `pvr` feature gates the whole driver, including this table.
pub fn emit_sf(entries: &[StidEntry], meta: &GenMeta<'_>) -> Result<String, ParseError> {
    if entries.is_empty() {
        return Err(ParseError(
            "stid_fmts: refusing to emit an empty validation table".into(),
        ));
    }

    // Sort by id. Upstream's table is declaration order (ABI for the strings,
    // not for lookup); binary search needs id order, and sorting here is what
    // makes two generate() calls produce identical bytes even if a future
    // header shuffled rows.
    let mut sorted: Vec<&StidEntry> = entries.iter().collect();
    sorted.sort_by_key(|e| e.id);

    let mut out = String::new();
    out.push_str("// SPDX-License-Identifier: MIT OR GPL-2.0-only\n");
    out.push_str("// Copyright (c) 2023 Imagination Technologies Ltd.\n");
    out.push_str("// K1 MUSE Book: generated PowerVR register and firmware ABI definitions.\n");
    out.push_str("//\n");
    out.push_str("// GENERATED by `pvr-regen` — DO NOT EDIT BY HAND.\n");
    out.push_str("// Source: pvr_rogue_fwif_sf.h (`stid_fmts[]`)\n");
    writeln!(out, "// Upstream commit: {}", meta.commit).unwrap();
    out.push_str(
        "// Re-run: cargo run --manifest-path kernel/core/comps/k1-musebook/pvr/regen/Cargo.toml -- --fetch\n",
    );
    out.push_str("//\n");
    out.push_str("// Format strings are emitted. They add a few tens of kilobytes of\n");
    out.push_str("// `.rodata` (775 templates). Accepted unconditionally: this crate has\n");
    out.push_str("// no feature flags of its own (the kernel's `pvr` feature already gates\n");
    out.push_str("// the whole driver), and a firmware trace that cannot be read on the\n");
    out.push_str("// board is dead weight of a worse kind. See `regen/src/emit_sf.rs`.\n");
    out.push_str("#![allow(dead_code)]\n");
    out.push_str("#![allow(missing_docs)]\n");
    out.push('\n');
    out.push_str("//! Firmware trace id and format-string table.\n");
    out.push_str("//!\n");
    out.push_str("//! Generated from upstream `stid_fmts[]` in `pvr_rogue_fwif_sf.h`.\n");
    out.push_str("//! Sorted by [`StidFmt::id`] for binary search; upstream's table is not.\n");
    out.push('\n');
    out.push_str("/// One row of upstream `stid_fmts[]`.\n");
    out.push_str("#[derive(Clone, Copy, Debug, PartialEq, Eq)]\n");
    out.push_str("pub struct StidFmt {\n");
    out.push_str("    /// Upstream `rogue_km_stid_fmt::id` (`ROGUE_FW_LOG_CREATESFID`).\n");
    out.push_str("    pub id: u32,\n");
    out.push_str("    /// `ROGUE_FW_SF_GID(id)` — ordinal in `enum rogue_fw_log_sfgroups`.\n");
    out.push_str("    pub group: u8,\n");
    out.push_str("    /// `ROGUE_FW_SF_PARAMNUM(id)` — argument words after the timestamp.\n");
    out.push_str("    pub params: u8,\n");
    out.push_str("    /// Upstream `rogue_km_stid_fmt::name` — C printf template.\n");
    out.push_str("    pub fmt: &'static str,\n");
    out.push_str("}\n");
    out.push('\n');
    writeln!(
        out,
        "/// Upstream `stid_fmts[]` ({} entries), sorted by [`StidFmt::id`].",
        sorted.len()
    )
    .unwrap();
    out.push_str("pub static STID_FMTS: &[StidFmt] = &[\n");
    for e in &sorted {
        writeln!(
            out,
            "    StidFmt {{ id: {}, group: {}, params: {}, fmt: {} }},",
            fmt_u32_hex(e.id),
            e.group,
            e.params,
            rust_string_literal(&e.fmt)
        )
        .unwrap();
    }
    out.push_str("];\n");
    out.push('\n');
    out.push_str("/// Looks up `id` in [`STID_FMTS`].\n");
    out.push_str("///\n");
    out.push_str("/// Ports upstream `find_sfid()` in `pvr_fw_trace.c`. A miss is `None`\n");
    out.push_str("/// rather than `ROGUE_FW_SF_LAST`: that sentinel's only job in upstream\n");
    out.push_str("/// is to mean \"not in the table\", which [`Option`] already says.\n");
    out.push_str("pub fn lookup(id: u32) -> Option<&'static StidFmt> {\n");
    out.push_str("    match STID_FMTS.binary_search_by_key(&id, |e| e.id) {\n");
    out.push_str("        Ok(i) => Some(&STID_FMTS[i]),\n");
    out.push_str("        Err(_) => None,\n");
    out.push_str("    }\n");
    out.push_str("}\n");
    Ok(out)
}

fn fmt_u32_hex(value: u32) -> String {
    format!("0x{:04x}_{:04x}", value >> 16, value & 0xffff)
}

/// A Rust string literal whose contents equal `s`.
fn rust_string_literal(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if c.is_ascii_graphic() || c == ' ' => out.push(c),
            c => write!(out, "\\u{{{:x}}}", u32::from(c)).unwrap(),
        }
    }
    out.push('"');
    out
}
