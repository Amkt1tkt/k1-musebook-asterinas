//! Emit `src/rogue/fwif.rs` from parsed FWIF structs + upstream layout asserts.

use std::{
    collections::{BTreeMap, BTreeSet},
    fmt::Write as _,
};

use crate::{
    emit::GenMeta,
    parse::ParseError,
    parse_fwif::{
        CField, CStruct, CType, Layout, LayoutAssert, asserted_types, dependency_closure,
        layout_struct,
    },
};

fn rust_type_name(c_name: &str) -> String {
    let mut out = String::new();
    let mut cap = true;
    for c in c_name.chars() {
        if c == '_' {
            cap = true;
            continue;
        }
        if cap {
            out.extend(c.to_uppercase());
            cap = false;
        } else {
            out.push(c);
        }
    }
    out
}

fn is_fw_addr_field(name: &str, ty: &CType) -> bool {
    matches!(ty, CType::U32) && (name == "fw_addr" || name.ends_with("_fw_addr"))
}

/// Emit the full `fwif.rs` source.
pub fn emit_fwif(
    structs: &BTreeMap<String, CStruct>,
    asserts: &[LayoutAssert],
    meta: &GenMeta<'_>,
) -> Result<String, ParseError> {
    let roots = asserted_types(asserts);
    for ty in &roots {
        if !structs.contains_key(ty) {
            return Err(ParseError(format!(
                "allow-list / check type `{ty}` was not parsed from fwif headers (totality)"
            )));
        }
    }
    let need = dependency_closure(&roots, structs);
    // Stable emission order: dependency-before-use via reverse topo-ish: emit
    // leaves first by sorting names, then rely on Rust allowing forward refs for
    // named structs. Nested anons are emitted as helper types before their parent.
    let mut names: Vec<&String> = need.iter().collect();
    names.sort();

    let mut cache: BTreeMap<String, Layout> = BTreeMap::new();
    for n in &names {
        layout_struct(n, structs, &mut cache)?;
    }

    let mut out = String::new();
    out.push_str("// SPDX-License-Identifier: MIT OR GPL-2.0-only\n");
    out.push_str("// Copyright (c) 2023 Imagination Technologies Ltd.\n");
    out.push_str("// K1 MUSE Book: generated PowerVR register and firmware ABI definitions.\n");
    out.push_str("//\n");
    out.push_str("// GENERATED by `pvr-regen` — DO NOT EDIT BY HAND.\n");
    out.push_str(
        "// Source: pvr_rogue_fwif.h, pvr_rogue_fwif_common.h, pvr_rogue_fwif_shared.h,\n",
    );
    out.push_str("//          pvr_rogue_fwif_client.h, pvr_rogue_fwif_dev_info.h,\n");
    out.push_str("//          pvr_rogue_fwif_resetframework.h, pvr_rogue_fwif_stream.h,\n");
    out.push_str(
        "//          pvr_rogue_mips.h, and the matching *_check.h layout-assert headers.\n",
    );
    out.push_str("// (`pvr_rogue_fwif_sf.h` is emitted separately into `sf.rs`.)\n");
    writeln!(out, "// Upstream commit: {}", meta.commit).unwrap();
    out.push_str(
        "// Re-run: cargo run --manifest-path kernel/core/comps/k1-musebook/pvr/regen/Cargo.toml -- --fetch\n",
    );
    out.push_str("//\n");
    out.push_str("// Dead code is expected: the check-file allow-list is the ABI surface the\n");
    out.push_str("// firmware shares with the host, including types without a runtime caller.\n");
    out.push_str("#![allow(dead_code)]\n");
    out.push_str("#![allow(missing_docs)]\n");
    out.push_str("#![allow(non_camel_case_types)]\n");
    out.push('\n');
    out.push_str("//! Structures shared with the GPU firmware.\n");
    out.push_str("//!\n");
    out.push_str(
        "//! Generated from upstream `pvr_rogue_fwif*.h` with every `offsetof`/`sizeof`\n",
    );
    out.push_str("//! assert from the matching `*_check.h` translated into `const` assertions.\n");
    out.push_str("//! A field at the wrong offset is a compile error, not a silent hang.\n");
    out.push('\n');
    out.push_str("/// An address in the firmware's own 32-bit address space.\n");
    out.push_str("///\n");
    out.push_str(
        "/// The firmware processor sees a different address space from both the CPU and\n",
    );
    out.push_str(
        "/// the GPU's rendering units. Mixing these up is the second most common porting\n",
    );
    out.push_str("/// error after structure layout, so it gets a newtype.\n");
    out.push_str("#[repr(transparent)]\n");
    out.push_str("#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Pod)]\n");
    out.push_str("pub struct FwAddr(pub u32);\n");
    out.push('\n');
    out.push_str("/// 4-byte cell for upstream `bool x __aligned(4)`.\n");
    out.push_str("///\n");
    out.push_str(
        "/// C keeps `bool` size 1 with align 4 (3 bytes of implicit pad before the next\n",
    );
    out.push_str(
        "/// field). Representing that as an explicit `u32` is Pod-safe and matches the\n",
    );
    out.push_str("/// byte span the following field sees.\n");
    out.push_str("pub type Bool4 = u32;\n");
    out.push('\n');
    out.push_str("/// Host pointer stored as `u64` (LP64). Firmware never dereferences these;\n");
    out.push_str("/// they exist so the host can cache a kernel VA beside the FW address.\n");
    out.push_str("pub type HostPtr = u64;\n");
    out.push('\n');

    // Emit nested anon helper types first (discovered while walking).
    let mut helpers: Vec<(String, Vec<CField>, bool, Option<u32>)> = Vec::new();
    for n in &names {
        let st = &structs[*n];
        collect_helpers(&st.fields, &rust_type_name(n), &mut helpers);
    }
    // Dedup by helper name, keep first.
    let mut seen_helpers = BTreeSet::new();
    for (hname, fields, is_union, align) in &helpers {
        if !seen_helpers.insert(hname.clone()) {
            continue;
        }
        if *is_union {
            emit_union(&mut out, hname, fields, structs, &mut cache)?;
        } else {
            emit_struct_with_fields(
                &mut out,
                hname,
                fields,
                *align,
                structs,
                &mut cache,
                &BTreeMap::new(),
            )?;
        }
    }

    for n in &names {
        let st = &structs[*n];
        let rname = rust_type_name(n);
        if st.bitfield_word {
            writeln!(out, "/// Upstream `struct {n}` (bitfield word).").unwrap();
            out.push_str("#[repr(transparent)]\n");
            out.push_str("#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Pod)]\n");
            writeln!(out, "pub struct {rname}(pub u32);\n").unwrap();
            continue;
        }
        // Detect if any field is a union-shaped nested type that we emit as union.
        writeln!(out, "/// Upstream `struct {n}`.").unwrap();
        emit_struct_with_fields(
            &mut out,
            &rname,
            &st.fields,
            st.align,
            structs,
            &mut cache,
            &anon_helper_map(n, &st.fields),
        )?;
    }

    // Feature / quirk / enhancement bit indices from dev_info.h are emitted as
    // plain consts by a separate pass in lib.rs into this file's tail — see
    // `emit_dev_info_bits`.

    out.push_str("\n/// Compile-time layout assertions transcribed from upstream `*_check.h`.\n");
    out.push_str("///\n");
    out.push_str("/// Expected numbers are upstream's; if Rust layout disagrees, the Rust side\n");
    out.push_str("/// is wrong — never edit the numbers to silence a failure.\n");
    out.push_str("mod layout_asserts {\n");
    out.push_str("    use super::*;\n");
    // `size_of` is in the prelude on our toolchain; only import `offset_of`.
    out.push_str("    use core::mem::offset_of;\n\n");

    // Group asserts by type for readability.
    let mut by_ty: BTreeMap<&str, Vec<&LayoutAssert>> = BTreeMap::new();
    for a in asserts {
        let ty = match a {
            LayoutAssert::Offset { ty, .. } | LayoutAssert::Size { ty, .. } => ty.as_str(),
        };
        by_ty.entry(ty).or_default().push(a);
    }
    for (ty, alist) in by_ty {
        let rname = rust_type_name(ty);
        writeln!(out, "    // struct {ty}").unwrap();
        for a in alist {
            match a {
                LayoutAssert::Size { size, .. } => {
                    writeln!(
                        out,
                        "    const _: () = assert!(size_of::<{rname}>() == {size});"
                    )
                    .unwrap();
                }
                LayoutAssert::Offset { member, offset, .. } => {
                    let expr = rust_offset_expr(&rname, member, structs)?;
                    writeln!(out, "    const _: () = assert!({expr} == {offset});").unwrap();
                }
            }
        }
        out.push('\n');
    }
    out.push_str("}\n");

    Ok(out)
}

fn anon_helper_map(parent: &str, fields: &[CField]) -> BTreeMap<String, String> {
    let mut m = BTreeMap::new();
    let base = rust_type_name(parent);
    for f in fields {
        if let CType::Nested { .. } = &f.ty {
            m.insert(
                f.name.clone(),
                format!("{base}{}", rust_field_suffix(&f.name)),
            );
        }
    }
    m
}

fn rust_field_suffix(name: &str) -> String {
    if let Some(rest) = name.strip_prefix("__anon") {
        format!("Anon{rest}")
    } else {
        // Concatenate without `_` so helper names stay UpperCamelCase
        // (`RogueFwifKccbCmdCmdData`, not `RogueFwifKccbCmd_CmdData`).
        rust_type_name(name)
    }
}

fn collect_helpers(
    fields: &[CField],
    parent_rust: &str,
    out: &mut Vec<(String, Vec<CField>, bool, Option<u32>)>,
) {
    for f in fields {
        if let CType::Nested {
            is_union,
            fields: nested,
        } = &f.ty
        {
            let hname = format!("{parent_rust}{}", rust_field_suffix(&f.name));
            collect_helpers(nested, &hname, out);
            out.push((hname, nested.clone(), *is_union, f.align));
        }
    }
}

fn emit_union(
    out: &mut String,
    name: &str,
    fields: &[CField],
    structs: &BTreeMap<String, CStruct>,
    cache: &mut BTreeMap<String, Layout>,
) -> Result<(), ParseError> {
    writeln!(out, "/// Anonymous / nested union `{name}`.").unwrap();
    out.push_str("#[repr(C)]\n");
    out.push_str("#[pod_union]\n");
    out.push_str("#[derive(Clone, Copy)]\n");
    writeln!(out, "pub union {name} {{").unwrap();
    for f in fields {
        let ty = rust_field_type(f, structs, cache, &BTreeMap::new())?;
        // Skip nested-in-union complexity: only named scalar/struct members.
        writeln!(out, "    pub {}: {},", f.name, ty).unwrap();
    }
    out.push_str("}\n\n");
    Ok(())
}

fn emit_struct_with_fields(
    out: &mut String,
    name: &str,
    fields: &[CField],
    align: Option<u32>,
    structs: &BTreeMap<String, CStruct>,
    cache: &mut BTreeMap<String, Layout>,
    helpers: &BTreeMap<String, String>,
) -> Result<(), ParseError> {
    // Build explicit-padded field list from layout.
    let lay = layout_fields_local(fields, false, align, structs, cache)?;
    if let Some(a) = align {
        writeln!(out, "#[repr(C, align({a}))]").unwrap();
    } else {
        out.push_str("#[repr(C)]\n");
    }
    // No `Debug`: structs may contain `#[pod_union]` fields, which are not Debug.
    out.push_str("#[derive(Clone, Copy, Pod)]\n");
    writeln!(out, "pub struct {name} {{").unwrap();

    let mut cursor = 0u64;
    let mut pad_i = 0usize;
    for f in fields {
        if f.is_bitfield {
            // Bitfield-only structs are handled elsewhere; mixed bitfields unsupported.
            return Err(ParseError(format!("{name}: mixed bitfields not supported")));
        }
        let field_off = *lay
            .offsets
            .get(&f.name)
            .ok_or_else(|| ParseError(format!("{name}.{} missing offset", f.name)))?;
        if field_off > cursor {
            let n = field_off - cursor;
            writeln!(out, "    pub __pad{pad_i}: [u8; {n}],").unwrap();
            pad_i += 1;
            cursor = field_off;
        }
        let ty = rust_field_type(f, structs, cache, helpers)?;
        let fname = rust_field_name(&f.name);
        writeln!(out, "    pub {fname}: {ty},").unwrap();
        let (esz, _) = field_elem_size_align(f, structs, cache)?;
        let count = f.count.unwrap_or(1);
        cursor += esz * count;
    }
    if lay.size > cursor {
        let n = lay.size - cursor;
        writeln!(out, "    pub __pad{pad_i}: [u8; {n}],").unwrap();
    }
    out.push_str("}\n\n");
    Ok(())
}

fn layout_fields_local(
    fields: &[CField],
    is_union: bool,
    align: Option<u32>,
    structs: &BTreeMap<String, CStruct>,
    cache: &mut BTreeMap<String, Layout>,
) -> Result<Layout, ParseError> {
    // For unions we only need size.
    if is_union {
        let mut max_size = 0u64;
        let mut max_align = 1u32;
        for f in fields {
            let (esz, ea) = field_elem_size_align(f, structs, cache)?;
            let count = f.count.unwrap_or(1).max(1);
            max_size = max_size.max(esz * count);
            max_align = max_align.max(ea);
        }
        if let Some(a) = align {
            max_align = max_align.max(a);
        }
        let size = ((max_size + max_align as u64 - 1) / max_align as u64) * max_align as u64;
        return Ok(Layout {
            size,
            align: max_align,
            offsets: BTreeMap::new(),
        });
    }
    // Fresh cache entry name every call — `__tmp` must not be reused across
    // different field lists or the layout cache returns a stale layout.
    static TEMP_ID: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(0);
    let id = TEMP_ID.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
    let tmp_name = format!("__tmp{id}");
    let tmp = CStruct {
        name: tmp_name.clone(),
        fields: fields.to_vec(),
        align,
        bitfield_word: false,
    };
    let mut map = structs.clone();
    map.insert(tmp_name.clone(), tmp);
    let lay = layout_struct(&tmp_name, &map, cache)?;
    cache.remove(&tmp_name);
    Ok(lay)
}

fn field_elem_size_align(
    f: &CField,
    structs: &BTreeMap<String, CStruct>,
    cache: &mut BTreeMap<String, Layout>,
) -> Result<(u64, u32), ParseError> {
    let (mut s, mut a) = match &f.ty {
        CType::U8 | CType::Bool => (1u64, 1u32),
        CType::U16 => (2, 2),
        CType::U32 => (4, 4),
        CType::U64 | CType::HostPtr => (8, 8),
        CType::Named(n) => {
            let l = layout_struct(n, structs, cache)?;
            (l.size, l.align)
        }
        CType::Nested { is_union, fields } => {
            let l = layout_fields_local(fields, *is_union, None, structs, cache)?;
            (l.size, l.align)
        }
    };
    if let Some(fa) = f.align {
        // `bool __aligned(4)` keeps size 1 in C, but for Bool4 we emit size 4.
        if matches!(f.ty, CType::Bool) && fa >= 4 {
            s = fa as u64;
            a = fa;
        } else {
            a = a.max(fa);
        }
    }
    Ok((s, a))
}

fn rust_field_type(
    f: &CField,
    structs: &BTreeMap<String, CStruct>,
    cache: &mut BTreeMap<String, Layout>,
    helpers: &BTreeMap<String, String>,
) -> Result<String, ParseError> {
    let base = match &f.ty {
        CType::U8 => "u8".into(),
        CType::U16 => "u16".into(),
        CType::U32 => {
            if is_fw_addr_field(&f.name, &f.ty) {
                "FwAddr".into()
            } else {
                "u32".into()
            }
        }
        CType::U64 => "u64".into(),
        CType::Bool => {
            if f.align.unwrap_or(1) >= 4 {
                "Bool4".into()
            } else {
                "u8".into()
            }
        }
        CType::HostPtr => "HostPtr".into(),
        CType::Named(n) => rust_type_name(n),
        CType::Nested { .. } => helpers
            .get(&f.name)
            .cloned()
            .ok_or_else(|| ParseError(format!("missing helper for {}", f.name)))?,
    };
    // Force layout cache touch for named.
    if let CType::Named(n) = &f.ty {
        let _ = layout_struct(n, structs, cache)?;
    }
    match f.count {
        None => Ok(base),
        Some(0) => Ok(format!("[{base}; 0]")),
        Some(n) => Ok(format!("[{base}; {n}]")),
    }
}

fn rust_field_name(name: &str) -> String {
    match name {
        "type" => "r#type".into(),
        "priv" => "r#priv".into(),
        "mod" => "r#mod".into(),
        other => other.to_string(),
    }
}

/// Translate a C member path into a const offset expression.
///
/// Plain fields use `offset_of!(Ty, field)`. Nested `geom_state[0].foo` becomes
/// arithmetic — Rust's `offset_of!` does not accept array indexes.
fn rust_offset_expr(
    outer: &str,
    member: &str,
    structs: &BTreeMap<String, CStruct>,
) -> Result<String, ParseError> {
    if !member.contains('[') && !member.contains('.') {
        return Ok(format!("offset_of!({outer}, {member})"));
    }
    // Pattern: field[idx].subfield  (form used by the pinned upstream checks).
    let re_idx = member
        .find('[')
        .ok_or_else(|| ParseError(format!("unsupported offset path `{member}`")))?;
    let field = &member[..re_idx];
    let rest = &member[re_idx + 1..];
    let end = rest
        .find(']')
        .ok_or_else(|| ParseError(format!("bad index in `{member}`")))?;
    let idx: u64 = rest[..end]
        .parse()
        .map_err(|e| ParseError(format!("index: {e}")))?;
    let after = rest[end + 1..].trim_start();
    let sub = after
        .strip_prefix('.')
        .ok_or_else(|| ParseError(format!("expected . after index in `{member}`")))?;
    // Resolve the element type of `field` on `outer`.
    let c_name = outer_to_c_name(outer);
    let st = structs
        .get(&c_name)
        .ok_or_else(|| ParseError(format!("no struct {c_name} for offset path")))?;
    let f = st
        .fields
        .iter()
        .find(|f| f.name == field)
        .ok_or_else(|| ParseError(format!("{c_name}.{field} missing")))?;
    let inner_ty = match &f.ty {
        CType::Nested { .. } => format!("{outer}{}", rust_field_suffix(field)),
        CType::Named(n) => rust_type_name(n),
        other => {
            return Err(ParseError(format!(
                "indexed field {field} has unexpected type {other:?}"
            )));
        }
    };
    let stride = match idx {
        0 => String::new(),
        1 => format!(" + size_of::<{inner_ty}>()"),
        n => format!(" + {n} * size_of::<{inner_ty}>()"),
    };
    Ok(format!(
        "offset_of!({outer}, {field}){stride} + offset_of!({inner_ty}, {sub})"
    ))
}

fn outer_to_c_name(rust: &str) -> String {
    // RogueFwifDmaAddr → rogue_fwif_dma_addr
    let mut out = String::new();
    for (i, c) in rust.chars().enumerate() {
        if c.is_uppercase() {
            if i > 0 {
                out.push('_');
            }
            out.extend(c.to_lowercase());
        } else {
            out.push(c);
        }
    }
    out
}

/// Emit bit-index constants from `pvr_rogue_fwif_dev_info.h`.
pub fn emit_dev_info_bits(dev_info_h: &str) -> Result<String, ParseError> {
    let text = crate::parse_fwif::preprocess_fwif(dev_info_h);
    let mut out = String::new();
    out.push_str("\n/// Bit indices from `pvr_rogue_fwif_dev_info.h`.\n");
    out.push_str("pub mod dev_info_bits {\n");

    // Three anonymous enums in order: BRN, ERN, FEATURE.
    let mut enums = Vec::new();
    let mut search = text.as_str();
    while let Some(pos) = search.find("enum {") {
        let after = &search[pos + 5..];
        let end = after.find('}').ok_or_else(|| ParseError("enum {".into()))?;
        enums.push(after[1..end].to_string());
        search = &after[end + 1..];
    }
    if enums.len() < 3 {
        return Err(ParseError(format!(
            "expected 3 enums in dev_info.h, found {}",
            enums.len()
        )));
    }
    let sections = [
        ("quirks", &enums[0]),
        ("enhancements", &enums[1]),
        ("features", &enums[2]),
    ];
    for (mod_name, body) in sections {
        writeln!(out, "    pub mod {mod_name} {{").unwrap();
        let mut next = 0u32;
        for part in body.split(',') {
            let part = part.trim();
            if part.is_empty() {
                continue;
            }
            let name = if let Some((n, v)) = part.split_once('=') {
                let n = n.trim();
                next = v.trim().parse::<u32>().unwrap_or(next);
                n
            } else {
                part
            };
            if name.ends_with("_MAX") {
                writeln!(out, "        pub const MAX: u32 = {next};").unwrap();
            } else {
                // PVR_FW_HAS_BRN_63142 → BRN_63142
                let short = name.strip_prefix("PVR_FW_HAS_").unwrap_or(name);
                writeln!(out, "        pub const {short}: u32 = {next};").unwrap();
                next += 1;
            }
        }
        out.push_str("    }\n");
    }
    out.push_str("}\n");
    Ok(out)
}

/// Emit the allow-listed object-like `#define`s from `pvr_rogue_fwif.h`.
///
/// The struct emitter above is driven by the `*_check.h` layout asserts, which
/// say nothing about bare constants, so these would otherwise have to be
/// hand-copied into the port. Every name in
/// [`FWIF_DEFINE_ALLOW_LIST`](crate::allow_list::FWIF_DEFINE_ALLOW_LIST) must
/// evaluate; one that does not is an error rather than a silent omission, which
/// is the same totality rule the register allow-list follows.
pub fn emit_fwif_defines(fwif_h: &str) -> Result<String, ParseError> {
    use crate::allow_list::FWIF_DEFINE_ALLOW_LIST;

    let all = crate::parse::parse_evaluable_defines(fwif_h, &BTreeMap::new())?;

    let mut out = String::new();
    out.push_str("\n/// Constants from `pvr_rogue_fwif.h` that belong to no structure.\n");
    out.push_str("///\n");
    out.push_str("/// Only the names on `pvr-regen`'s FWIF define allow-list appear here.\n");
    out.push_str("pub mod defines {\n");
    for entry in FWIF_DEFINE_ALLOW_LIST {
        let value = all.get(entry.name).ok_or_else(|| {
            ParseError(format!(
                "allow-list define `{}` not evaluated from pvr_rogue_fwif.h — {}",
                entry.name, entry.why
            ))
        })?;
        let value = u32::try_from(*value).map_err(|_| {
            ParseError(format!(
                "allow-list define `{}` is {:#x}, which does not fit the u32 the \
                 firmware ABI declares",
                entry.name, value
            ))
        })?;
        writeln!(out, "    /// Upstream `{}`.", entry.name).unwrap();
        writeln!(
            out,
            "    pub const {}: u32 = {};",
            entry.name,
            fmt_u32_hex(value)
        )
        .unwrap();
    }
    out.push_str("}\n");
    Ok(out)
}

/// Eight hex digits in two underscore-separated groups, as the other emitters
/// spell 64-bit values.
fn fmt_u32_hex(value: u32) -> String {
    format!("0x{:04x}_{:04x}", value >> 16, value & 0xffff)
}

/// Coverage stats for the final report / tests.
pub fn assert_coverage(asserts: &[LayoutAssert]) -> (usize, usize) {
    let mut offsets = 0usize;
    let mut sizes = 0usize;
    for a in asserts {
        match a {
            LayoutAssert::Offset { .. } => offsets += 1,
            LayoutAssert::Size { .. } => sizes += 1,
        }
    }
    (offsets, sizes)
}
